import fs from 'node:fs/promises'
import {chromium} from '../../.tools/qa/node_modules/playwright/index.mjs'
import {assert,ok,login,fixture,base,suffix,test,save} from './helpers.mjs'

const browser=await chromium.launch({executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true})
const context=await browser.newContext({viewport:{width:1440,height:1000}})
const page=await context.newPage(),errors=[],scanRequests=[]
page.setDefaultTimeout(15000)
page.on('pageerror',e=>errors.push(e.message))
page.on('request',r=>{if(r.url().endsWith('/api/station/scan'))scanRequests.push(r)})
const guestInput=()=>page.getByPlaceholder('请扫描条码，登录后开始作业')
const loginDialog=()=>page.getByRole('dialog',{name:'登录后开始扫码作业'})
try{
  await login();const f=await fixture()
  const account='entry'+suffix,password='Op9-'+crypto.randomUUID()
  const user=await ok('/api/admin/users',{account,name:'扫码登录验证员',role:'Operator',password})
  await ok('/api/admin/grants',{userId:user.id,stationId:f.stations[0].id})
  const main='MC'+(suffix+'1').padStart(12,'0')

  await test('未登录直接进入工位页面，只有一个扫码输入框，后台仍拒绝匿名过站',async()=>{
    await page.goto(base+'/station')
    await page.getByRole('heading',{name:'工位工作台',exact:true}).waitFor()
    await page.waitForFunction(()=>!document.querySelector('input')?.disabled)
    assert.equal(await page.getByRole('dialog').count(),0)
    assert.equal(await page.locator('input:visible').count(),1)
    assert.equal(scanRequests.length,0)
    const response=await fetch(base+'/api/station/scan',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({requestId:crypto.randomUUID(),stationId:f.stations[0].id,batchId:f.batch.id,code:main})})
    assert.equal(response.status,401)
    await fs.mkdir(new URL('../../.local/screenshots/',import.meta.url),{recursive:true})
    await page.screenshot({path:new URL('../../.local/screenshots/station-guest.png',import.meta.url).pathname.replace(/^\/([A-Z]:)/,'$1'),fullPage:true})
  })
  await test('首次扫描提示登录；取消和错误密码均不提交过站',async()=>{
    await guestInput().fill('MC'+(suffix+'0').padStart(12,'0'));await guestInput().press('Enter')
    await loginDialog().waitFor();await loginDialog().getByRole('button',{name:'取消',exact:true}).click()
    await loginDialog().waitFor({state:'hidden'});assert.equal(scanRequests.length,0)
    await guestInput().fill(main);await guestInput().press('Enter')
    await loginDialog().locator('input[autocomplete="username"]').fill(account)
    await loginDialog().locator('input[autocomplete="current-password"]').fill('wrong-password')
    await loginDialog().getByRole('button',{name:'登录并继续',exact:true}).click()
    await page.getByText('账号或密码错误',{exact:true}).waitFor()
    assert.equal(scanRequests.length,0)
  })
  await test('登录后只列授权工位，选择工单并加载 SOP 后自动提交首次条码且仅计一次',async()=>{
    await loginDialog().locator('input[autocomplete="current-password"]').fill(password)
    await loginDialog().getByRole('button',{name:'登录并继续',exact:true}).click()
    const chooser=page.getByRole('dialog',{name:'切换授权工位与工单'})
    await chooser.waitFor();await loginDialog().waitFor({state:'hidden'})
    await chooser.locator('.el-select').nth(0).click()
    assert.equal(await page.getByRole('option').count(),1)
    await page.getByRole('option',{name:f.stations[0].code+' · '+f.stations[0].name,exact:true}).click()
    await chooser.locator('.el-select').nth(1).click();await page.getByRole('option',{name:f.order.code,exact:true}).click()
    await chooser.locator('.el-select').nth(2).click();await page.getByRole('option',{name:f.batch.code,exact:true}).click()
    await chooser.getByRole('button',{name:'进入工位',exact:true}).click()
    await page.getByRole('heading',{name:'主码过站成功',exact:true}).waitFor()
    assert.equal(scanRequests.length,1)
    assert.equal(JSON.parse(scanRequests[0].postData()).code,main)
    assert.equal((await ok('/api/station/summary?stationId='+f.stations[0].id+'&batchId='+f.batch.id)).done,1)
    await chooser.waitFor({state:'hidden'});assert.equal(await page.locator('input:visible').count(),1)
  })
  await test('已登录无需点击重置即可继续扫描；退出返回免登录页且再次扫码要求认证',async()=>{
    assert.equal(await page.getByRole('button',{name:'重新扫描主码',exact:true}).count(),0)
    const scan=page.getByPlaceholder('请扫描主码',{exact:true})
    await scan.fill(main);await scan.press('Tab')
    await page.getByRole('heading',{name:'已过站，未重复计数',exact:true}).waitFor()
    await page.getByRole('button',{name:'退出',exact:true}).click()
    await page.getByRole('heading',{name:'工位工作台',exact:true}).waitFor()
    await guestInput().fill(main);await guestInput().press('Tab');await loginDialog().waitFor()
    assert.equal(scanRequests.length,2)
    assert.equal(await page.getByText('最近过站记录',{exact:true}).count(),0)
  })
  await test('PC 入口仍要求登录，页面无未处理脚本异常',async()=>{
    await page.goto(base+'/pc');await page.getByRole('heading',{name:'登录生产工作台',exact:true}).waitFor()
    assert.deepEqual(errors,[])
  })
}finally{await browser.close();await save('station-entry')}
