"""One-time, reproducible upstream SQL/mapper adaptation. Development tooling only.

The generated Flyway SQL is committed and executed by Java; Python is not an
installation dependency. Run only against an unmodified pinned upstream copy.
"""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1] / 'ruoyi-server'
source = (root / 'sql/ry_20260417.sql').read_text(encoding='utf-8-sig')
skip_seeds = {'sys_dept', 'sys_user', 'sys_post', 'sys_role', 'sys_user_role',
              'sys_role_menu', 'sys_role_dept', 'sys_user_post', 'sys_job', 'sys_notice'}
output = ['-- PostgreSQL adaptation of pinned RuoYi 3.9.2 schema. No demo accounts.']
indexes = []
table = None
identities = []
for line in source.splitlines():
    if line.lower().startswith('drop table '):
        continue
    match = re.match(r'create table (\w+)', line, re.I)
    if match:
        table = match[1]
    match = re.match(r'insert into (\w+)', line, re.I)
    if match and (match[1] in skip_seeds or 'sys.user.initPassword' in line):
        continue
    line = re.sub(r"\s+comment\s+'(?:[^']|'')*'", '', line, flags=re.I)
    if 'auto_increment' in line and not line.startswith(')'):
        identities.append((table, line.split()[0]))
    line = re.sub(r'\b(bigint|int|tinyint)\(\d+\)', lambda m: 'bigint' if m[1] == 'bigint' else 'integer', line)
    line = re.sub(r'\bdatetime\b', 'timestamp', line)
    line = re.sub(r'\b(longblob|longtext)\b', 'text', line)
    line = line.replace('not null auto_increment', 'generated by default as identity')
    line = re.sub(r'^\) engine=.*', ');', line)
    line = re.sub(r'\bunique key (\w+)', r'constraint \1 unique', line)
    index = re.match(r'\s*key (\w+)\s*(\(.+\)),?$', line)
    if index:
        indexes.append(f'create index {index[1]} on {table} {index[2]};')
        continue
    line = line.replace('sysdate()', 'CURRENT_TIMESTAMP')
    output.append(line)
sql = '\n'.join(output)
sql = re.sub(r',\s*\);', '\n);', sql)
sql += '\n' + '\n'.join(indexes) + '\n'
for table, column in identities:
    sql += f"select setval(pg_get_serial_sequence('{table}', '{column}'), greatest(coalesce(max({column}), 0) + 1, 100), false) from {table};\n"
sql += """
-- Framework data scopes use membership in the comma-separated ancestor path.
create function find_in_set(bigint, text) returns boolean
language sql immutable strict as $$ select $1::text = any(string_to_array($2, ',')) $$;
create unique index uk_sys_user_name_active on sys_user(user_name) where del_flag = '0';
create unique index uk_sys_config_key on sys_config(config_key);
insert into sys_dept(dept_id, parent_id, ancestors, dept_name, status, del_flag)
values(100, 0, '0', '聚星制造', '0', '0');
insert into sys_role(role_id, role_name, role_key, role_sort, data_scope, menu_check_strictly, dept_check_strictly, status, del_flag)
values(1, '超级管理员', 'admin', 1, '1', 1, 1, '0', '0');
-- No administrator password in SQL. Bootstrap reads an operator-provided secret file.
"""
target = root / 'ruoyi-mes/src/main/resources/db/migration/V1__ruoyi_postgresql.sql'
target.parent.mkdir(parents=True, exist_ok=True)
target.write_text(sql, encoding='utf-8')

for path in root.glob('*/src/main/resources/mapper/**/*.xml'):
    text = path.read_text(encoding='utf-8')
    text = text.replace('sysdate()', 'CURRENT_TIMESTAMP').replace('ifnull(', 'coalesce(').replace('`query`', 'query')
    text = re.sub(r"date_format\((.+?),'%Y%m%d'\)", r'CAST(\1 AS date)', text)
    text = re.sub(r'\bstatus = 0\b', "status = '0'", text)
    text = text.replace('cast(notice_content as char)', 'notice_content')
    if 'insert ignore' in text:
        text = text.replace('insert ignore into', 'insert into')
        text = text.replace('    </insert>', '        on conflict (user_id, notice_id) do nothing\n    </insert>')
    path.write_text(text, encoding='utf-8')
